export interface EvalLine {
  tx: Transaction;
  truth: Category;
}

export function evalSet(): EvalLine[] {
  const build = (rows: Row[], country: CountryCode, currency: string) =>
    rows.map(([rawLabel, amount, truth], i) => ({
      truth,
      tx: {
        id: `eval-${country}-${i}`,
        accountId: `eval-${country}`,
        date: `2026-10-${String((i % 28) + 1).padStart(2, '0')}`,
        amount,
        currency,
        country,
        rawLabel,
        // Internal transfers are matched across accounts in the app; here the truth is given.
        isInternalTransfer: truth === 'internal_transfer' ? true : undefined,
      },
    }));
  return [...build(EN, 'US', 'USD'), ...build(FR, 'FR', 'EUR')];
}
